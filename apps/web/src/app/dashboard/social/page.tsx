"use client";

import { useEffect, useState } from "react";
import { TopNav } from "@/components/TopNav";
import { api } from "@essentials/api-client";

interface Post {
  id: string; content: string; platforms: string[]; mediaUrl?: string | null;
  status: string; scheduledAt?: string | null; results?: Record<string, { status: string; detail: string }>;
  createdAt: string;
}
interface Accounts { autoPublish: string[]; manual: string[]; composerLinks: Record<string, string> }

const ALL = [
  { key: "x", label: "X (Twitter)" },
  { key: "telegram", label: "Telegram" },
  { key: "discord", label: "Discord" },
  { key: "facebook", label: "Facebook" },
  { key: "youtube", label: "YouTube" },
  { key: "tiktok", label: "TikTok" },
  { key: "instagram", label: "Instagram" },
  { key: "mixcloud", label: "Mixcloud" },
  { key: "webhook", label: "Webhook / Zapier" },
];

/** Central social media hub: AI-generated copy → post to every platform. */
export default function SocialHub() {
  const [accounts, setAccounts] = useState<Accounts | null>(null);
  const [posts, setPosts] = useState<Post[]>([]);
  const [content, setContent] = useState("");
  const [topic, setTopic] = useState("");
  const [venue, setVenue] = useState("The Warehouse, Cape Town");
  const [eventDate, setEventDate] = useState("");
  const [selected, setSelected] = useState<string[]>(["x", "instagram"]);
  const [generating, setGenerating] = useState(false);
  const [posting, setPosting] = useState(false);
  const [schedule, setSchedule] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [msg, setMsg] = useState<string | null>(null);

  const load = () => {
    api.get<Accounts>("/social/accounts").then(setAccounts).catch((e) => setError(e.message));
    api.get<Post[]>("/social/posts").then(setPosts).catch(() => {});
  };
  useEffect(() => { load(); }, []);

  const togglePlatform = (key: string) =>
    setSelected((p) => (p.includes(key) ? p.filter((x) => x !== key) : [...p, key]));

  const generate = async () => {
    if (!topic.trim()) return;
    setGenerating(true); setError(null);
    try {
      const res = await api.post<{ posts: Record<string, string> }>("/social/generate", {
        topic, platforms: selected.length ? selected : ALL.map((a) => a.key),
        includeHashtags: true, venue, eventDate: eventDate || undefined,
      });
      const first = Object.values(res.posts)[0];
      if (first) setContent(first);
      setMsg("Copy generated by the local agent — edit if you like, then post.");
    } catch (err: any) { setError("Generation failed: " + err.message); }
    finally { setGenerating(false); }
  };

  const createPost = async (scheduled?: string) => {
    if (!content.trim() || !selected.length) return;
    setPosting(true); setError(null);
    try {
      await api.post("/social/posts", {
        content, platforms: selected, mediaUrl: undefined,
        scheduledAt: scheduled || schedule || undefined,
      });
      setMsg(scheduled || schedule ? "Post scheduled." : "Posted to selected platforms.");
      setContent("");
      load();
    } catch (err: any) { setError(err.message); }
    finally { setPosting(false); }
  };

  const publishAgain = async (id: string) => {
    try { await api.post(`/social/posts/${id}/publish`, {}); load(); setMsg("Republished."); }
    catch (err: any) { setError(err.message); }
  };

  const isAuto = (key: string) => accounts?.autoPublish.includes(key);
  const input = "w-full bg-bg border border-line rounded-lg px-3 py-2";

  return (
    <>
      <TopNav />
      <main className="max-w-4xl mx-auto px-6 py-8 space-y-6">
        <h1 className="text-2xl font-black tracking-wide">SOCIAL MEDIA HUB</h1>
        <p className="text-neutral-500 text-sm">
          One composer, every platform. Copy is written by the local AI agent; auto-publish runs on
          configured platforms ({accounts?.autoPublish.join(", ") || "none configured yet"}), the rest get a
          copy button + composer link.
        </p>
        {error && <p className="text-red-400 text-sm">{error}</p>}
        {msg && <p className="text-neon text-sm">{msg}</p>}

        <section className="border border-line bg-surface rounded-xl p-4 space-y-3">
          <h2 className="font-bold text-neon uppercase text-sm tracking-wider">1 · Generate with the local agent</h2>
          <div className="grid md:grid-cols-3 gap-3">
            <input className={input} placeholder="Topic — e.g. Amapiano Sunrise this Friday!" value={topic} onChange={(e) => setTopic(e.target.value)} />
            <input className={input} placeholder="Venue (optional)" value={venue} onChange={(e) => setVenue(e.target.value)} />
            <input className={input} placeholder="Date (optional)" value={eventDate} onChange={(e) => setEventDate(e.target.value)} />
          </div>
          <button onClick={generate} disabled={generating || !topic.trim()}
            className="bg-neon text-bg font-black rounded-lg px-5 py-2 tracking-widest disabled:opacity-50">
            {generating ? "WRITING…" : "✦ GENERATE COPY"}
          </button>
        </section>

        <section className="border border-line bg-surface rounded-xl p-4 space-y-3">
          <h2 className="font-bold text-neon uppercase text-sm tracking-wider">2 · Platforms</h2>
          <div className="flex flex-wrap gap-2">
            {ALL.map((p) => (
              <button key={p.key} onClick={() => togglePlatform(p.key)}
                className={`rounded-lg px-3 py-2 text-sm border ${selected.includes(p.key) ? "border-neon text-neon" : "border-line text-neutral-400"}`}>
                {p.label} {isAuto(p.key) ? "· auto" : "· manual"}
              </button>
            ))}
          </div>
        </section>

        <section className="border border-line bg-surface rounded-xl p-4 space-y-3">
          <h2 className="font-bold text-neon uppercase text-sm tracking-wider">3 · Post</h2>
          <textarea className={`${input} h-40`} value={content} onChange={(e) => setContent(e.target.value)}
            placeholder="Your post text (generate it above or write your own)" />
          <div className="grid md:grid-cols-3 gap-3 items-end">
            <div>
              <span className="text-xs text-neutral-400 uppercase tracking-wider">Schedule (optional)</span>
              <input type="datetime-local" className={`${input} mt-1`} value={schedule} onChange={(e) => setSchedule(e.target.value)} />
            </div>
            <button onClick={() => createPost()} disabled={posting || !content.trim() || !selected.length}
              className="bg-neon text-bg font-black rounded-lg py-2 tracking-widest disabled:opacity-50">
              {posting ? "POSTING…" : "POST NOW"}
            </button>
            <button onClick={() => createPost(schedule)} disabled={posting || !content.trim() || !schedule}
              className="border border-neon text-neon font-bold rounded-lg py-2 tracking-wide disabled:opacity-50">SCHEDULE</button>
          </div>
          {accounts && accounts.manual.some((m) => selected.includes(m)) && (
            <div className="text-xs text-neutral-400 space-y-1">
              <p>Manual platforms in this post (copy the text, then open):</p>
              {selected.filter((s) => accounts.manual.includes(s)).map((s) => (
                <a key={s} href={accounts.composerLinks[s]} target="_blank" className="block text-neon underline">{s} composer →</a>
              ))}
            </div>
          )}
        </section>

        <section className="border border-line rounded-xl overflow-hidden">
          <h2 className="font-bold text-neon uppercase text-sm tracking-wider p-4 pb-2">POST HISTORY</h2>
          {posts.map((p) => (
            <div key={p.id} className="border-t border-line px-4 py-3 text-sm">
              <div className="flex justify-between items-center">
                <span className={`font-bold ${p.status === "published" ? "text-neon" : p.status === "failed" ? "text-red-400" : "text-neutral-400"}`}>
                  {p.status.toUpperCase()}
                </span>
                <span className="text-neutral-500 text-xs">{new Date(p.createdAt).toLocaleString()}</span>
              </div>
              <p className="mt-1 whitespace-pre-wrap">{p.content.slice(0, 200)}{p.content.length > 200 ? "…" : ""}</p>
              <p className="text-neutral-500 text-xs mt-1">{p.platforms.join(" · ")}
                {p.results && Object.entries(p.results).map(([k, v]) => ` · ${k}: ${v.status}`).join("")}
              </p>
              {p.status !== "published" && (
                <button onClick={() => publishAgain(p.id)} className="text-neon underline text-xs mt-1">Retry publish</button>
              )}
            </div>
          ))}
          {!posts.length && <p className="px-4 py-6 text-center text-neutral-500 text-sm">No posts yet.</p>}
        </section>
      </main>
    </>
  );
}
